-- Student/password identity mapping and explicit approval state. Additive and rerunnable.
ALTER TABLE dbo.users ADD COLUMN IF NOT EXISTS schoolemail varchar(320);
ALTER TABLE dbo.users ADD COLUMN IF NOT EXISTS authsubject uuid;
ALTER TABLE dbo.users ADD COLUMN IF NOT EXISTS approvalstatus varchar(20);
ALTER TABLE dbo.users ADD COLUMN IF NOT EXISTS rejectionreason varchar(500);
UPDATE dbo.users u SET approvalstatus=CASE WHEN r.rolename IN ('Staff','Admin') THEN 'approved' ELSE 'pending' END FROM dbo.roles r WHERE r.roleid=u.roleid AND u.approvalstatus IS NULL;
ALTER TABLE dbo.users ALTER COLUMN approvalstatus SET DEFAULT 'pending';
ALTER TABLE dbo.users ALTER COLUMN approvalstatus SET NOT NULL;
DO $$ BEGIN ALTER TABLE dbo.users ADD CONSTRAINT ck_users_approval CHECK (approvalstatus IN ('pending','approved','rejected','suspended')); EXCEPTION WHEN duplicate_object THEN NULL; END $$;
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_schoolid_normalized ON dbo.users(lower(trim(schoolid)));
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_authsubject ON dbo.users(authsubject) WHERE authsubject IS NOT NULL;

CREATE TABLE IF NOT EXISTS dbo.approvalhistory(
  approvalhistoryid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  accountuserid integer NOT NULL REFERENCES dbo.users(userid),
  action varchar(20) NOT NULL CHECK(action IN ('pending','approved','rejected','suspended')),
  actingadminuserid integer REFERENCES dbo.users(userid),
  reason varchar(500),
  createdat timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_approvalhistory_account_created ON dbo.approvalhistory(accountuserid,createdat DESC);
REVOKE ALL ON dbo.approvalhistory FROM anon,authenticated;
REVOKE ALL ON dbo.users FROM anon,authenticated;

-- The app now creates users only through the service-role endpoint. This hook blocks browser sign-up.
CREATE OR REPLACE FUNCTION public.hook_restrict_bulldogs_signup(event jsonb) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
BEGIN
  IF current_user='supabase_auth_admin' AND coalesce(event->'user'->>'email','') LIKE '%@auth.bulldogs-xchange.invalid' THEN RETURN '{}'::jsonb; END IF;
  RETURN jsonb_build_object('error',jsonb_build_object('http_code',403,'message','Use Bulldogs Xchange registration.'));
END; $$;
