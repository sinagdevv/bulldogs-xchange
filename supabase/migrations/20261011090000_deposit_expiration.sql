  ('ReservationDepositAmount','200.00','Decimal','Required refundable deposit per reservation, capped at order total'),
  ('DepositDeadlineHours','24','Integer','Hours allowed to submit a reservation deposit'),
  ('PickupDeadlineOperatingDays','3','Integer','Campus operating days allowed after Ready for Pickup')
ON CONFLICT (settingkey) DO NOTHING;

