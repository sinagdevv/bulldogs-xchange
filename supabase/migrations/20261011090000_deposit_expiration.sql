BEGIN;
SET TRANSACTION ISOLATION LEVEL SERIALIZABLE;

ALTER TABLE dbo.reservationstatuses DROP CONSTRAINT IF EXISTS reservationstatuses_statusname_check;
ALTER TABLE dbo.reservationstatuses ADD CONSTRAINT reservationstatuses_statusname_check
  CHECK(statusname IN ('Pending','Pending Deposit','Confirmed','Preparing','Ready for Pickup','Completed','Cancelled','Expired'));

INSERT INTO dbo.reservationstatuses(statusname)
VALUES('Pending Deposit')
ON CONFLICT (statusname) DO NOTHING;

INSERT INTO dbo.paymentmethods(paymentmethodname,isactive)
VALUES('GCash',true)
ON CONFLICT (paymentmethodname) DO UPDATE SET isactive=true;

ALTER TABLE dbo.reservations
  ADD COLUMN IF NOT EXISTS depositdeadlineat timestamptz,
  ADD COLUMN IF NOT EXISTS depositpaymentmethodid bigint REFERENCES dbo.paymentmethods(paymentmethodid),
  ADD COLUMN IF NOT EXISTS depositpolicyversion varchar(40),
  ADD COLUMN IF NOT EXISTS depositgraceuntil timestamptz,
  ADD COLUMN IF NOT EXISTS readyat timestamptz,
  ADD COLUMN IF NOT EXISTS pickupdeadlineat timestamptz,
  ADD COLUMN IF NOT EXISTS expiredat timestamptz,
  ADD COLUMN IF NOT EXISTS inventoryreleasedat timestamptz;

ALTER TABLE dbo.transactions
  ADD COLUMN IF NOT EXISTS pickupbalanceamount numeric(12,2),
  ADD COLUMN IF NOT EXISTS receiptreference varchar(200);
CREATE UNIQUE INDEX IF NOT EXISTS uq_transactions_receiptreference
  ON dbo.transactions(lower(receiptreference)) WHERE receiptreference IS NOT NULL;

CREATE TABLE IF NOT EXISTS dbo.campusclosures(
  closuredate date PRIMARY KEY,
  title varchar(200) NOT NULL,
  createdbyuserid bigint REFERENCES dbo.users(userid),
  createdat timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS dbo.counteroperatinghours(
  weekday smallint PRIMARY KEY CHECK(weekday BETWEEN 0 AND 6),
  opensat time NOT NULL,
  closesat time NOT NULL CHECK(closesat>opensat),
  isopen boolean NOT NULL DEFAULT true,
  updatedat timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS dbo.reservationdeposits(
  reservationdepositid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reservationid bigint NOT NULL UNIQUE REFERENCES dbo.reservations(reservationid),
  customerid bigint NOT NULL REFERENCES dbo.users(userid),
  expectedamount numeric(12,2) NOT NULL CHECK(expectedamount>0),
  amountreceived numeric(12,2) CHECK(amountreceived IS NULL OR amountreceived>=0),
  paymentmethodid bigint REFERENCES dbo.paymentmethods(paymentmethodid),
  paymentreference varchar(200),
  cashcollectedbyuserid bigint REFERENCES dbo.users(userid),
  cashcollectedat timestamptz,
  cashreconciledbyuserid bigint REFERENCES dbo.users(userid),
  cashreconciledat timestamptz,
  evidencemetadata jsonb NOT NULL DEFAULT '{}'::jsonb CHECK(jsonb_typeof(evidencemetadata)='object'),
  verificationstatus varchar(40) NOT NULL DEFAULT 'Awaiting Payment' CHECK(verificationstatus IN ('Awaiting Payment','Submitted for Verification','Verified','Rejected','Refund Pending','Refunded','Refund Failed')),
  submittedat timestamptz,
  verifiedbyuserid bigint REFERENCES dbo.users(userid),
  verifiedat timestamptz,
  rejectedat timestamptz,
  rejectionreason varchar(500),
  createdat timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedat timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK(verificationstatus<>'Verified' OR (amountreceived IS NOT NULL AND verifiedbyuserid IS NOT NULL AND verifiedat IS NOT NULL)),
  CHECK(amountreceived IS NULL OR amountreceived<=expectedamount)
);

CREATE TABLE IF NOT EXISTS dbo.depositrefunds(
  depositrefundid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reservationdepositid bigint NOT NULL UNIQUE REFERENCES dbo.reservationdeposits(reservationdepositid),
  refundamount numeric(12,2) NOT NULL CHECK(refundamount>0),
  refundstatus varchar(30) NOT NULL DEFAULT 'Refund Pending' CHECK(refundstatus IN ('Refund Pending','Refund Approved','Refund Held','Payout Recorded','Refund Completed','Refund Failed')),
  refundreference varchar(200),
  approvedbyuserid bigint REFERENCES dbo.users(userid),
  approvedat timestamptz,
  approvalreason varchar(500),
  requiresadminreview boolean NOT NULL DEFAULT false,
  exceptionreason varchar(500),
  assignedtouserid bigint REFERENCES dbo.users(userid),
  payoutrecordedbyuserid bigint REFERENCES dbo.users(userid),
  payoutrecordedat timestamptz,
  confirmedbyuserid bigint REFERENCES dbo.users(userid),
  confirmedat timestamptz,
  evidencemetadata jsonb NOT NULL DEFAULT '{}'::jsonb CHECK(jsonb_typeof(evidencemetadata)='object'),
  requestedat timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  processedbyuserid bigint REFERENCES dbo.users(userid),
  processedat timestamptz,
  failurereason varchar(500),
  updatedat timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK(refundstatus<>'Refund Completed' OR (refundreference IS NOT NULL AND payoutrecordedbyuserid IS NOT NULL AND confirmedbyuserid IS NOT NULL AND confirmedat IS NOT NULL)),
  CHECK(approvedbyuserid IS NULL OR approvedbyuserid IS DISTINCT FROM payoutrecordedbyuserid),
  CHECK(payoutrecordedbyuserid IS NULL OR payoutrecordedbyuserid IS DISTINCT FROM confirmedbyuserid)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_reservationdeposits_paymentreference
  ON dbo.reservationdeposits(lower(paymentreference)) WHERE paymentreference IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_depositrefunds_refundreference
  ON dbo.depositrefunds(lower(refundreference)) WHERE refundreference IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_reservations_depositdeadline
  ON dbo.reservations(depositdeadlineat) WHERE depositdeadlineat IS NOT NULL AND expiredat IS NULL;
CREATE INDEX IF NOT EXISTS ix_reservations_pickupdeadline
  ON dbo.reservations(pickupdeadlineat) WHERE pickupdeadlineat IS NOT NULL AND expiredat IS NULL;
CREATE INDEX IF NOT EXISTS ix_reservationdeposits_status
  ON dbo.reservationdeposits(verificationstatus,updatedat);
CREATE INDEX IF NOT EXISTS ix_depositrefunds_status
  ON dbo.depositrefunds(refundstatus,requestedat);
CREATE INDEX IF NOT EXISTS ix_depositrefunds_admin_review
  ON dbo.depositrefunds(requiresadminreview,refundstatus,requestedat);
CREATE INDEX IF NOT EXISTS ix_depositrefunds_assigned
  ON dbo.depositrefunds(assignedtouserid,refundstatus,updatedat);
CREATE UNIQUE INDEX IF NOT EXISTS uq_outbox_financial_scheduled_event
  ON dbo.automationoutbox(eventtype,aggregatetype,aggregateid)
  WHERE eventtype IN ('DEPOSIT_DEADLINE_REMINDER','PICKUP_DEADLINE_REMINDER','LOW_STOCK_ALERT','DAILY_OPERATIONS_SUMMARY');

