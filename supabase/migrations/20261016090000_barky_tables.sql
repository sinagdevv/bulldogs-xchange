-- Barky AI chatbot tables.
-- Additive migration: only CREATE TABLE/INDEX IF NOT EXISTS, no drops or data mutations.
-- user_id is a bare BIGINT with no FK — avoids cross-schema constraint fragility.
BEGIN;

CREATE TABLE IF NOT EXISTS dbo.bx_barky_sessions (
  id          uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id     bigint,                        -- NULL = guest; no FK to keep migration safe
  ip_hash     varchar(64),
  created_at  timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at  timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS dbo.bx_barky_messages (
  id          uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  session_id  uuid        NOT NULL REFERENCES dbo.bx_barky_sessions(id) ON DELETE CASCADE,
  role        varchar(16) NOT NULL CHECK (role IN ('user','assistant','system')),
  content     text        NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_bx_barky_messages_session_created
  ON dbo.bx_barky_messages (session_id, created_at);

CREATE TABLE IF NOT EXISTS dbo.bx_barky_faq (
  id          bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  question    text        NOT NULL,
  answer      text        NOT NULL,
  is_active   boolean     NOT NULL DEFAULT true,
  created_at  timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at  timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE dbo.bx_barky_sessions IS 'Barky AI chat sessions (guest and authenticated)';
COMMENT ON TABLE dbo.bx_barky_messages IS 'Per-session chat message history for Barky AI';
COMMENT ON TABLE dbo.bx_barky_faq     IS 'Admin-managed FAQ entries injected into Barky system prompt';

-- Grant the application runtime role access.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'bulldogs_app_runtime') THEN
    GRANT SELECT, INSERT, UPDATE, DELETE
      ON TABLE dbo.bx_barky_sessions, dbo.bx_barky_messages, dbo.bx_barky_faq
      TO bulldogs_app_runtime;
    GRANT USAGE, SELECT
      ON SEQUENCE dbo.bx_barky_faq_id_seq
      TO bulldogs_app_runtime;
  END IF;
END $$;

COMMIT;
