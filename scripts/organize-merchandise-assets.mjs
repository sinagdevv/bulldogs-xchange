import {copyFile, mkdir, readFile, writeFile} from "node:fs/promises";
import path from "node:path";

const manifestPath="docs/merchandise-image-manifest.csv";
const root="frontend/public/images/products";
const slug=value=>value.trim().replace(/[^a-z0-9]+/gi,"-").toLowerCase();
const legacyWebp=source=>`/merch/${slug(path.dirname(source).split(/[\\/]/).at(-1))}-${slug(path.parse(source).name)}.webp`;
const lines=(await readFile(manifestPath,"utf8")).trim().split(/\r?\n/);
const rows=lines.slice(1).map(line=>line.split(","));
const skuCounts=rows.reduce((counts,row)=>(counts[row[2]]=(counts[row[2]]??0)+1,counts),{});

const destinations=rows.map(row=>{
  const [source,,sku]=row;
  const sourceStem=path.parse(source).name.toUpperCase();
  const gender=sourceStem.match(/_(F|M)$/)?.[1];
  let stem=skuCounts[sku]>1&&gender?`${sku}-${gender}`:sku;
  return {row,stem,department:source.includes("/SHS/")?"SHS":"COL"};
});
const stemCounts=destinations.reduce((counts,item)=>(counts[item.stem]=(counts[item.stem]??0)+1,counts),{});

for(const item of destinations){
  if(stemCounts[item.stem]>1) item.stem=`${item.stem}-${item.department}`;
  const folder=item.row[3]?"approved":"showcase";
  const destination=`/images/products/${folder}/${item.stem}-FRONT.webp`;
  await mkdir(path.join(root,folder),{recursive:true});
  await copyFile(path.join("frontend/public",legacyWebp(item.row[0])),path.join("frontend/public",destination));
  item.row[1]=destination;
}

await Promise.all(["fallback","assets/originals","assets/processing-review"].map(dir=>mkdir(dir,{recursive:true})));
await writeFile(manifestPath,[lines[0],...destinations.map(({row})=>row.join(",")),""].join("\n"));
await writeFile("frontend/src/showcase-assets.ts",`// Generated by scripts/organize-merchandise-assets.mjs\nexport const SHOWCASE_ASSETS=${JSON.stringify(destinations.map(({row})=>({source:row[0],src:row[1],approved:Boolean(row[3])})),null,2)} as const;\n`);
